// Generates the SYNTHETIC example files in data/. Not an ANSYS export.
#include <cmath>
#include <cstdio>
#include <fstream>
#include <string>

#include "fea1d.hpp"

int main(int argc, char** argv) {
    const std::string dir = argc > 1 ? argv[1] : "data";
    const double L = 1.0, R = 0.0056419;  // radius giving A = pi R^2 = 1e-4 m^2
    const int seg = 24;
    const double pi = std::acos(-1.0);

    // --- ASCII STL: closed cylinder along x ---
    std::ofstream s(dir + "/example_rod.stl");
    s << "solid example_rod\n";
    auto tri = [&](double a[3], double b[3], double c[3]) {
        double u[3] = {b[0] - a[0], b[1] - a[1], b[2] - a[2]}, v[3] = {c[0] - a[0], c[1] - a[1], c[2] - a[2]};
        double n[3] = {u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]};
        double m = std::sqrt(n[0] * n[0] + n[1] * n[1] + n[2] * n[2]);
        if (m > 0) for (double& q : n) q /= m;
        char buf[512];
        std::snprintf(buf, sizeof buf,
                      "  facet normal %.6e %.6e %.6e\n    outer loop\n      vertex %.6e %.6e %.6e\n      vertex %.6e %.6e %.6e\n      vertex %.6e %.6e %.6e\n    endloop\n  endfacet\n",
                      n[0], n[1], n[2], a[0], a[1], a[2], b[0], b[1], b[2], c[0], c[1], c[2]);
        s << buf;
    };
    for (int i = 0; i < seg; ++i) {
        double a0 = 2 * pi * i / seg, a1 = 2 * pi * (i + 1) / seg;
        double p0[3] = {0, R * std::cos(a0), R * std::sin(a0)}, p1[3] = {0, R * std::cos(a1), R * std::sin(a1)};
        double q0[3] = {L, p0[1], p0[2]}, q1[3] = {L, p1[1], p1[2]};
        double c0[3] = {0, 0, 0}, c1[3] = {L, 0, 0};
        tri(p0, q0, q1);
        tri(p0, q1, p1);
        tri(c0, p1, p0);  // cap x=0 (normal -x)
        tri(c1, q0, q1);  // cap x=L (normal +x)
    }
    s << "endsolid example_rod\n";

    // --- SYNTHETIC nodal temperature CSV: FE rod profile + small radial term ---
    wb::RodProblem p;
    std::ofstream c(dir + "/example_nodal_temperature_SYNTHETIC.csv");
    c << "# SYNTHETIC data generated by tools/gen_examples.cpp. NOT an ANSYS export.\n";
    c << "# Units: x_m,y_m,z_m in metres; temperature_C in degrees Celsius.\n";
    c << "# T = analytical rod profile T(x) with a small made-up radial rise toward the axis.\n";
    c << "node_id,x_m,y_m,z_m,temperature_C\n";
    int id = 1;
    const int stations = 21, ring = 12;
    for (int i = 0; i < stations; ++i) {
        double x = L * i / (stations - 1);
        double T = wb::exactTemperature(p, x);
        char buf[200];
        std::snprintf(buf, sizeof buf, "%d,%.6f,%.6f,%.6f,%.4f\n", id++, x, 0.0, 0.0, T + 0.5);
        c << buf;
        for (int j = 0; j < ring; ++j) {
            double a = 2 * pi * j / ring;
            std::snprintf(buf, sizeof buf, "%d,%.6f,%.6f,%.6f,%.4f\n", id++, x, R * std::cos(a), R * std::sin(a), T);
            c << buf;
        }
    }
    return 0;
}
